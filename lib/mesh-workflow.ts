// ── Workflow Engine ──────────────────────────────────────────────────

export async function runMeshWorkflow(
    mesh: MeshCoordinator,
    taskDescription: string,
    outputDir: string
): Promise<WorkflowResult> {
    const startTime = Date.now();

    // Ensure output directory exists
    fs.mkdirSync(path.join(outputDir, 'src'), { recursive: true });

    const steps: WorkflowStep[] = [
        { agent: 'architect', intent: `Design architecture: ${taskDescription}`, artifacts: [], status: 'pending' },
        { agent: 'builder', intent: `Implement code: ${taskDescription}`, dependsOn: ['architect'], artifacts: [], status: 'pending' },
        { agent: 'auditor', intent: `Security review: ${taskDescription}`, dependsOn: ['builder'], artifacts: [], status: 'pending' },
        { agent: 'ops', intent: `Deploy config: ${taskDescription}`, dependsOn: ['auditor'], artifacts: [], status: 'pending' },
        { agent: 'analyst', intent: `Build report: ${taskDescription}`, dependsOn: ['ops'], artifacts: [], status: 'pending' },
    ];

    const allArtifacts: WorkflowArtifact[] = [];
    const messages: MeshMessage[] = [];

    for (const step of steps) {
        step.status = 'running';
        step.startedAt = Date.now();

        // Route through mesh for resonance scoring
        const meshResult = await mesh.dispatch(step.intent);
        step.result = meshResult.agentResult;

        // Generate real artifacts based on agent role
        switch (step.agent) {
            case 'architect':
                step.artifacts = architectDesign(taskDescription);
                break;
            case 'builder':
                step.artifacts = builderImplement(taskDescription);
                break;
            case 'auditor':
                step.artifacts = auditorReview(taskDescription);
                break;
            case 'ops':
                step.artifacts = opsDeployConfig(taskDescription);
                break;
            case 'analyst':
                step.artifacts = analystReport(taskDescription, allArtifacts, steps);
                break;
        }

        // Write artifacts to disk
        for (const artifact of step.artifacts) {
            const filePath = path.join(outputDir, artifact.filename);
            fs.mkdirSync(path.dirname(filePath), { recursive: true });
            fs.writeFileSync(filePath, artifact.content, 'utf-8');
        }

        allArtifacts.push(...step.artifacts);

        // Inter-agent message
        if (step.dependsOn) {
            for (const dep of step.dependsOn) {
                messages.push({
                    id: `wf-${messages.length + 1}`,
                    from: dep,
                    to: step.agent,
                    intent: `Handoff: ${dep} → ${step.agent}`,
                    payload: { artifactCount: step.artifacts.length },
                    timestamp: Date.now()
                });
            }
        }

        step.completedAt = Date.now();
        step.status = 'complete';
    }

    const plan: WorkflowPlan = {
        name: 'PRZ Health Service',
        description: taskDescription,
        steps,
        outputDir
    };

    return {
        plan,
        success: steps.every(s => s.status === 'complete'),
        totalArtifacts: allArtifacts.length,
        agentMessages: messages,
        duration: Date.now() - startTime
    };
}
