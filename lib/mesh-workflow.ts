async function handleQueuePost(req: http.IncomingMessage, res: http.ServerResponse, requestId: string): Promise<void> {
  const body = await readBody(req);
  try {
    const parsed = JSON.parse(body);
    const message: PriorityMessage = {
      id: randomUUID(),
      priority: parsed.priority || 'normal',
      payload: parsed.payload,
      timestamp: Date.now(),
      source: parsed.source || 'api'
    };

    const accepted = priorityQueue.enqueue(message);
    if (accepted) {
      log('INFO', 'Message enqueued', { messageId: message.id, priority: message.priority });
      respond(res, 201, { success: true, data: { messageId: message.id }, timestamp: new Date().toISOString(), requestId }, requestId);
    } else {
      respond(res, 429, { success: false, error: 'Queue at capacity', timestamp: new Date().toISOString(), requestId }, requestId);
    }
  } catch {
    respond(res, 400, { success: false, error: 'Invalid JSON body', timestamp: new Date().toISOString(), requestId }, requestId);
  }
}

